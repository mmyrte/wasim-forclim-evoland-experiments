#!/usr/bin/env python3
"""Check methods 10/11 and station precipitation correction against 48-step WaSiM dumps.

usage: meteo_interpolation.py DUMP_DIR CONTROL_FILE CASE_DIR [--backend embedded|gtfn_cpu]
       [--static-dir DIR] [--steps N]
CONTROL_FILE.intern, generated by the reference run, provides resolved WaSiM parameters.
Static grids default to DUMP_DIR/../01/<doubs|rhone>_static. Data stays outside this repository.
"""

import argparse
import json
import re
import time
from datetime import datetime, timedelta
from pathlib import Path

import gt4py.next as gtx
import numpy as np
from wasim_dump import Dump
from wasim_gt.fields import I, J
from wasim_gt.processes.meteo_interpolation import (
    correct_precipitation_profile,
    distance_weights,
    fit_regression,
    interpolate_point,
    meteo_interpolation,
    precipitation_factor,
    rotate_coordinates,
)


def sections(control):
    translated = Path(str(control) + ".intern")
    text = translated.read_text(encoding="latin1")
    result = {}
    for name, body in re.findall(r"^\[([^\]]+)\]([^\[]*)", text, re.MULTILINE):
        result[name] = [
            line.split("#", 1)[0].strip()
            for line in body.splitlines()
            if line.split("#", 1)[0].strip()
        ]
    return result


def parameters(lines):
    if int(lines[0]) not in (10, 11):
        raise ValueError("Only interpolation methods 10 and 11 are supported")
    if int(lines[17]) != 0:
        raise ValueError("Scenario interpolation is outside the validated scope")
    inv = list(map(float, lines[2].split()))
    return {
        "method": int(lines[0]),
        "missing": float(lines[7]),
        "power": float(lines[8]),
        "fraction": float(lines[9]),
        "radius": float(lines[10]),
        "angle": float(lines[11]) * (3.14159265359 / 180.0),
        "anisotropy": float(lines[12]),
        "lower": float(lines[13]),
        "lower_value": float(lines[14]),
        "upper": float(lines[15]),
        "upper_value": float(lines[16]),
        "factor": float(lines[5]),
        "fit": (
            inv[0],
            inv[1],
            inv[2],
            int(inv[3]),
            inv[4],
            inv[5] if len(inv) > 5 else -9999.0,
        ),
    }


def station_data(path, missing):
    lines = Path(path).read_text(encoding="latin1").splitlines()
    metadata = [np.array(list(map(float, line.split()[4:]))) for line in lines[1:4]]
    records = {}
    for line in lines[5:]:
        tok = line.split()
        if len(tok) != len(metadata[0]) + 4:
            continue
        year, month, day, hour = map(int, tok[:4])
        if year == month == day == 0:
            break
        if year < 100:
            year += 1900
        dt = datetime(year, month, day) + timedelta(hours=hour)
        if dt in records:
            raise ValueError(f"Duplicate timestamp in {path}: {dt}")
        values = np.array(list(map(float, tok[4:])))
        records[dt] = np.where(
            (values < -missing) | (values > missing), -missing - 1.0, values
        )
    return (*metadata, records)


def compare(reference, candidate, active, nodata=-9999.0):
    """Return finite maximum and mismatch mask; never discard a nonfinite mismatch."""
    if reference.shape != candidate.shape:
        raise ValueError("Shape mismatch")
    same_special = (np.isnan(reference) & np.isnan(candidate)) | (
        (reference == candidate) & (~np.isfinite(reference) | (reference == nodata))
    )
    finite = (
        np.isfinite(reference)
        & np.isfinite(candidate)
        & (reference != nodata)
        & (candidate != nodata)
    )
    mismatch = active & ~(same_special | (finite & (reference == candidate)))
    delta = np.abs(reference[active & finite] - candidate[active & finite])
    return float(delta.max(initial=0.0)), mismatch


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("dump_dir", type=Path)
    ap.add_argument("control_file", type=Path)
    ap.add_argument("case_dir", type=Path)
    ap.add_argument("--backend", choices=["embedded", "gtfn_cpu"], default="embedded")
    ap.add_argument("--static-dir", type=Path)
    ap.add_argument("--steps", type=int, default=48)
    ap.add_argument("--json", type=Path)
    args = ap.parse_args()
    start = time.perf_counter()
    d = Dump(args.dump_dir)
    s = sections(args.control_file)
    case = "doubs" if args.case_dir.name == "Doubs" else "rhone"
    static = Dump(args.static_dir or args.dump_dir.parent / "01" / f"{case}_static")
    z = static("start", "[elevation_model]")[0]
    zone = static("start", "[zone_grid]")[0]
    x = static("start", "CoordX")[0]
    y = static("start", "CoordY")[0]
    nodata = -9999.0
    active = (zone != nodata) & np.isfinite(zone)
    assert z.shape == d("start", "temperature").shape[1:]
    elevation_path = Path(s["zone_grid"][0].split()[0])
    with elevation_path.open(encoding="latin1") as f:
        header = [f.readline().split() for _ in range(6)]
    if header[0][0].lower() != "ncols" or header[1][0].lower() != "nrows":
        raise ValueError("Expected an ASCII reference elevation-grid header")
    if (int(header[1][1]), int(header[0][1])) != z.shape:
        raise ValueError("Elevation-grid header and dump shapes differ")
    origin = (float(header[2][1]), float(header[3][1]))
    nodata = float(header[5][1])
    active = (zone != nodata) & np.isfinite(zone)
    dom = gtx.domain({I: z.shape[0], J: z.shape[1]})
    fld = lambda a: gtx.as_field(dom, np.broadcast_to(a, z.shape).copy())
    names = s["meteo_names"][: int(s["meteo_data_count"][0])]
    cfg = {n: parameters(s[n]) for n in names}
    data = {n: station_data(s[n][1].split()[0], cfg[n]["missing"]) for n in names}
    weights = {}
    rotated = {}
    worst = {n: 0.0 for n in names}
    fail = False
    first_failure = None
    for n in names:
        h, sx, sy, _ = data[n]
        c = cfg[n]
        if c["anisotropy"] < 1.0:
            rx, ry = rotate_coordinates(x, y, origin, c["angle"], nodata)
            sx, sy = rotate_coordinates(sx, sy, origin, c["angle"])
            for axis, actual in [("X", rx), ("Y", ry)]:
                grid = f"Coord{axis}Rot_{n}"
                reference = d("after_meteo", grid)
                actual_steps = np.broadcast_to(actual, reference.shape)
                diff, bad = compare(
                    reference,
                    actual_steps,
                    np.broadcast_to(active, reference.shape),
                    nodata,
                )
                worst[grid] = diff
                fail |= bool(bad.any())
                if bad.any():
                    print("GEOMETRY DIFF", grid, np.argwhere(bad)[0], diff, flush=True)
        else:
            rx, ry = x, y
        rotated[n] = (sx, sy)
        weights[n] = [
            fld(w)
            for w in distance_weights(
                rx, ry, sx, sy, c["power"], c["radius"], c["anisotropy"]
            )
        ]
    pc = list(
        map(float, [line.split()[0] for line in s["precipitation_correction"][:6]])
    )
    hour, day, month, year = map(int, s["model_time"][:4])
    first = datetime(year, month, day) + timedelta(hours=hour)
    steps = min(args.steps, d("start", "temperature").shape[0])
    times = []
    assert d("start", "temperature").shape[0] == 48
    for step in range(steps):
        t0 = time.perf_counter()
        dt = first + timedelta(hours=step)
        values = {n: data[n][3][dt].copy() for n in names}
        same = {
            n: len({float(v) for v in values[n] if v >= -cfg[n]["missing"]}) <= 1
            for n in names
        }
        fits = {}
        for n in names:
            h, sx, sy, _ = data[n]
            lo, hi, tol, over, cluster, lapse = cfg[n]["fit"]
            fits[n] = fit_regression(
                sx,
                sy,
                h,
                values[n],
                lo,
                hi,
                tol,
                over,
                cluster,
                cfg[n]["missing"],
                lapse,
            )

        def query(n, xx, yy, height, fits=fits, values=values):
            sx, sy = rotated[n]
            c = {k: v for k, v in cfg[n].items() if k != "fit"}
            return interpolate_point(
                fits[n],
                sx,
                sy,
                values[n],
                xx,
                yy,
                height,
                origin=origin,
                nodata=nodata,
                **c,
            )

        def correction(p, temp, wind):
            return precipitation_factor(
                p,
                temp,
                wind,
                pc[1],
                (pc[2], pc[3]),
                (pc[4], pc[5]),
                cfg["temperature"]["missing"],
                cfg["wind_speed"]["missing"],
                cfg["precipitation"]["missing"],
            )

        if pc[0]:
            h, sx, sy, _ = data["precipitation"]
            values["precipitation"] = np.array(
                [
                    correction(
                        float(v),
                        query("temperature", float(xx), float(yy), float(hh)),
                        query("wind_speed", float(xx), float(yy), float(hh)),
                    )
                    for v, xx, yy, hh in zip(
                        values["precipitation"], sx, sy, h, strict=True
                    )
                ]
            )

            def profile(height, p):
                return correction(
                    p,
                    query("temperature", nodata, nodata, height),
                    query("wind_speed", nodata, nodata, height),
                )

            fits["precipitation"] = correct_precipitation_profile(
                fits["precipitation"],
                profile,
                float(z[active].max()),
                missing=cfg["precipitation"]["missing"],
            )
        for n in names:
            c = cfg[n]
            r = fits[n]
            # The legacy constructor disables regional regression with if ((1==2)&&(rarray)).
            options = {
                k: c[k]
                for k in (
                    "method",
                    "missing",
                    "fraction",
                    "factor",
                    "lower",
                    "lower_value",
                    "upper",
                    "upper_value",
                )
            }
            out = meteo_interpolation(
                fld(x),
                fld(y),
                fld(z),
                r,
                weights[n],
                values[n],
                fld(d("start", n)[step]),
                gtx.as_field(dom, active),
                dom,
                equal_stations=same[n],
                nodata=nodata,
                backend=args.backend,
                **options,
            ).asnumpy()
            reference = d("after_meteo", n)[step]
            diff, bad = compare(reference, out, active, nodata)
            worst[n] = max(worst[n], diff)
            if bad.any():
                fail = True
                if first_failure is None:
                    i, j = map(int, np.argwhere(bad)[0])
                    first_failure = {
                        "grid": n,
                        "step": step,
                        "timestamp": dt.isoformat(),
                        "cell": [i, j],
                        "expected": float(reference[i, j]),
                        "actual": float(out[i, j]),
                        "height": float(z[i, j]),
                        "x": float(x[i, j]),
                        "y": float(y[i, j]),
                        "raw_stations": data[n][3][dt].tolist(),
                        "corrected_stations": values[n].tolist(),
                        "coefficients": repr(r),
                        "parameters": c,
                    }
                    print("FIRST FAILURE", json.dumps(first_failure), flush=True)
        times.append(time.perf_counter() - t0)
        if step % 12 == 0:
            print("step", step, dt, flush=True)
    result = {
        "case": case,
        "backend": args.backend,
        "steps": steps,
        "active": int(active.sum()),
        "worst": worst,
        "first_failure": first_failure,
        "seconds": time.perf_counter() - start,
        "step_seconds": times,
        "parameters": cfg,
        "regional_regression": False,
    }
    print(json.dumps(result, indent=2), flush=True)
    if args.json:
        args.json.write_text(json.dumps(result, indent=2))
    return int(fail)


if __name__ == "__main__":
    raise SystemExit(main())
